"""Generate portable chain error classification from the Python SDK."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "sdk/python"))
from bittensor._generated.errors import ERRORS
from bittensor.error_map import (
    CUSTOM_TRANSACTION_ERRORS,
    DISPATCH_ERRORS,
    INVALID_TRANSACTION_ERRORS,
    NAME_TO_CODE,
    ErrorCode,
)
from bittensor.result import _SUBSTRING_FALLBACK

values = {
    "ErrorCode": {item.name: item.value for item in ErrorCode},
    "CHAIN_ERROR_CODES": NAME_TO_CODE,
    "CUSTOM_TRANSACTION_ERRORS": CUSTOM_TRANSACTION_ERRORS,
    "INVALID_TRANSACTION_ERRORS": INVALID_TRANSACTION_ERRORS,
    "DISPATCH_ERROR_CODES": {name: value[0] for name, value in DISPATCH_ERRORS.items()},
    "CHAIN_ERROR_CATALOG": [
        {"palletIndex": key[0], "errorIndex": key[1], "pallet": info.pallet,
         "name": info.name, "docs": info.docs}
        for key, info in ERRORS.items()
    ],
    "ERROR_SUBSTRING_FALLBACK": _SUBSTRING_FALLBACK,
}
output = "// Generated by scripts/generate-error-catalog.py. Do not edit by hand.\n"
for name, value in values.items():
    output += f"export const {name} = " + json.dumps(value, indent=2) + " as const\n\n"
output = output.rstrip() + "\n"
path = ROOT / "sdk/bittensor-ts/src/error-catalog.ts"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != output:
        raise SystemExit("Chain error catalog drift: run scripts/generate-error-catalog.py")
else:
    path.write_text(output)
print(f"Chain error catalog: {len(ERRORS)} module errors, {len(ErrorCode)} semantic codes")
