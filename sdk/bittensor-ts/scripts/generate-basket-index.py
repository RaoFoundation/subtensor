"""Generate frozen browser basket pricing data from the Python SDK snapshot."""
from __future__ import annotations

import argparse
import json
import runpy
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
source = runpy.run_path(str(ROOT / "sdk/python/bittensor/basket_index_data.py"))
names = {
    "EPOCH_BLOCK": "BASKET_INDEX_EPOCH_BLOCK",
    "GENERATED_BLOCK": "BASKET_INDEX_GENERATED_BLOCK",
    "SAMPLE_STEP": "BASKET_INDEX_SAMPLE_STEP",
    "INDEX": "BASKET_INDEX_SERIES",
    "TR_INDEX": "BASKET_TR_INDEX_SERIES",
    "BASELINES": "BASKET_BASELINES",
}
output = "// Generated by scripts/generate-basket-index.py; do not edit by hand.\n"
for name, export in names.items():
    output += f"export const {export} = " + json.dumps(source[name], indent=2, sort_keys=True) + " as const\n"
path = ROOT / "sdk/bittensor-ts/src/basket-index-data.ts"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != output:
        raise SystemExit("basket index data drift: run scripts/generate-basket-index.py")
else:
    path.write_text(output)
print(f"Basket index: {len(source['INDEX'])} samples, {len(source['BASELINES'])} baselines")
