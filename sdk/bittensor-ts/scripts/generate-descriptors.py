"""Generate portable TypeScript descriptors/builders from the Python metadata snapshot."""
import argparse
import ast
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
OUT = ROOT / 'sdk/bittensor-ts/src/descriptors.ts'
SOURCE = ROOT / 'sdk/python/bittensor/_generated'
p = argparse.ArgumentParser()
p.add_argument('--check', action='store_true')
args = p.parse_args()
lines = ["// Generated by scripts/generate-descriptors.py from the shared Python metadata snapshot.", "import type { ScaleValue } from './types'", "export type GeneratedCall = [string, string, Record<string, ScaleValue>]", ""]
counts = {}
for source, export, ctor in [('storage', 'storage', 'Item'), ('constants', 'constants', 'Item'), ('runtime_apis', 'runtimeApi', 'Method')]:
 lines.append(f'export const {export} = Object.freeze({{')
 count = 0
 for cls in ast.parse((SOURCE / f'{source}.py').read_text()).body:
  if not isinstance(cls, ast.ClassDef): continue
  entries = []
  for node in cls.body:
   if isinstance(node, ast.Assign) and isinstance(node.value, ast.Call) and isinstance(node.value.func, ast.Name) and node.value.func.id == ctor:
    container, name = [ast.literal_eval(v) for v in node.value.args[:2]]
    entries.append(f'    {node.targets[0].id}: [{json.dumps(container)}, {json.dumps(name)}] as const,')
  if entries:
   lines.extend([f'  {cls.name}: Object.freeze({{', *entries, '  }),'])
   count += len(entries)
 lines.extend(['})', ''])
 counts[export] = count
lines.extend(['export const runtimeApis = runtimeApi', '', 'export const calls = Object.freeze({'])
count = 0
call_schemas = []
for cls in ast.parse((SOURCE / 'calls.py').read_text()).body:
 if not isinstance(cls, ast.ClassDef): continue
 functions = [f for f in cls.body if isinstance(f, ast.FunctionDef) and f.name != '__iter__']
 if not functions or cls.name == 'Call': continue
 lines.append(f'  {cls.name}: Object.freeze({{')
 for fn in functions:
  returns = [s for s in fn.body if isinstance(s, ast.Return)]
  if not returns or not isinstance(returns[-1].value, ast.Call): continue
  call = returns[-1].value
  module, method = [ast.literal_eval(v) for v in call.args[:2]]
  params = call.args[2]
  keys = [ast.literal_eval(key) for key in params.keys]
  safe_name = lambda name: name + '_' if name in {'new', 'class', 'function', 'default', 'delete', 'in', 'var', 'const', 'let', 'switch', 'case'} else name
  names = [safe_name(arg.arg) for arg in fn.args.args]
  def ts_type(arg):
   annotation = ast.literal_eval(arg.annotation) if isinstance(arg.annotation, ast.Constant) else ''
   if annotation in ('bool',): return 'boolean'
   if annotation in ('u8', 'u16', 'u32', 'i16', 'MechId', 'NetUid', 'Percent', 'PerU16'): return 'number'
   if annotation in ('u64', 'u128', 'i64', 'TaoBalance', 'AlphaBalance', 'U256'): return 'bigint | number | string'
   if annotation in ('AccountId32', 'H160', 'H256'): return 'string | Uint8Array'
   return 'ScaleValue'
  signature = ', '.join(f'{safe_name(arg.arg)}: {ts_type(arg)}' for arg in fn.args.args)
  body = ', '.join(f'{json.dumps(key)}: {name}' for key, name in zip(keys, names))
  lines.append(f'    {fn.name}({signature}): GeneratedCall {{ return [{json.dumps(module)}, {json.dumps(method)}, {{ {body} }}] }},')
  call_schemas.append({"pallet": module, "function": method, "args": keys})
  count += 1
 lines.append('  }),')
lines.extend(['})', ''])
counts['calls'] = count
lines.extend(['export const callDescriptors = ' + json.dumps(call_schemas, indent=2) + ' as const', ''])
text = '\n'.join(lines)
if args.check:
 if OUT.read_text() != text: raise SystemExit('descriptor drift; run scripts/generate-descriptors.py')
else: OUT.write_text(text)
print(counts)
