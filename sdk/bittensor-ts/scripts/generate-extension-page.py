"""Embed the shared extension bridge page for the published Node package."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[3]
source = root / 'sdk/python/bittensor/extension/static/bridge.html'
target = root / 'sdk/bittensor-ts/src/extension-page.ts'
text = '// Generated by scripts/generate-extension-page.py; shared browser extension UI.\nexport const EXTENSION_BRIDGE_HTML = ' + json.dumps(source.read_text()) + '\n'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    if target.read_text() != text:
        raise SystemExit('extension bridge page drift; run scripts/generate-extension-page.py')
else:
    target.write_text(text)
