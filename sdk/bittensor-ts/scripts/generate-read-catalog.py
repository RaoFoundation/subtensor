import argparse
import ast
import json
import pathlib

parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
root = pathlib.Path(__file__).resolve().parents[3]
rows=[]
for path in sorted((root/'sdk/python/bittensor/reads').glob('*.py')):
 tree=ast.parse(path.read_text())
 for node in tree.body:
  if isinstance(node,(ast.FunctionDef,ast.AsyncFunctionDef)):
   for dec in node.decorator_list:
    if isinstance(dec,ast.Call) and isinstance(dec.func,ast.Name) and dec.func.id=='read':
     kw={k.arg:k.value for k in dec.keywords}
     params=ast.literal_eval(dec.args[1]) if len(dec.args)>1 else {}
     defaults={arg.arg:ast.literal_eval(default) for arg,default in zip(node.args.args[-len(node.args.defaults):],node.args.defaults)} if node.args.defaults else {}
     rows.append(dict(name=ast.literal_eval(dec.args[0]),category=ast.literal_eval(kw['category']),params=params,defaults=defaults,summary=(ast.get_docstring(node) or '').split('\n')[0]))
  if isinstance(node,ast.Expr) and isinstance(node.value,ast.Call) and isinstance(node.value.func,ast.Name) and node.value.func.id in ('scalar_read','_hyperparam'):
   call=node.value; kw={k.arg:k.value for k in call.keywords}; hyper=call.func.id=='_hyperparam'; per=hyper or ast.literal_eval(kw['per_netuid'])
   rows.append(dict(name=ast.literal_eval(call.args[0]),category='Hyperparameters' if hyper else ast.literal_eval(kw['category']),params={'netuid':'integer'} if per else {},defaults={},summary=ast.literal_eval(call.args[2] if hyper else kw['doc'])))
rows.sort(key=lambda r:r['name'])
text='// Read names and parameter contracts mirror sdk/python/bittensor/reads.\nexport const READ_CATALOG = '+json.dumps(rows,indent=2)+' as const\n\nexport interface ReadParams {\n'
for row in rows:
 ps=[]
 for key,typ in row['params'].items():
  t={'integer':'number','number':'number | string','boolean':'boolean','string':'string','array':'number[]' if key=='netuids' else 'string[]'}[typ]
  if row['defaults'].get(key,'x') is None:t+=' | null'
  ps.append(f"{key}{'?' if key in row['defaults'] else ''}: {t}")
 text+=f"  {row['name']}: {{ {'; '.join(ps)} }}\n"
text+='}\nexport type ReadName = keyof ReadParams\n'
text = text.replace('export interface ReadParams {', 'export type ReadAddress = string | { ss58Address?: string; ss58_address?: string; address?: string; coldkeypub?: ReadAddress | Promise<ReadAddress>; hotkeypub?: ReadAddress | Promise<ReadAddress> }\n\nexport interface ReadParams {')
for row in rows:
 for key in row['params']:
  if key.endswith('_ss58s'):
   text = text.replace(key + ': string[]', key + ': ReadAddress[]')
  elif key.endswith('_ss58'):
   text = text.replace(key + ': string', key + ': ReadAddress').replace(key + '?: string', key + '?: ReadAddress')
target = root / 'sdk/bittensor-ts/src/read-catalog.ts'
if args.check:
 if target.read_text() != text:
  raise SystemExit('TypeScript read catalog drift; run scripts/generate-read-catalog.py')
else:
 target.write_text(text)
print('Read count:',len(rows))

category_names = {
 'Accounts & keys': 'Accounts', 'Chain': 'Chain', 'Subnets': 'Subnets',
 'Staking': 'Staking', 'Epochs & timing': 'Epochs', 'Hyperparameters': 'Hyperparameters',
 'Delegation': 'Delegation', 'Neurons & registration': 'Neurons',
 'Leases & crowdloans': 'Leasing', 'Mining & collateral': 'Collateral',
 'Locks & conviction': 'Locks', 'Identity & commitments': 'Identity',
 'Weights & bonds': 'Weights', 'Prices & swaps': 'Prices',
}
namespace_text = "// Generated by scripts/generate-read-catalog.py.\nimport { READ_CATALOG, dispatchRead, type ReadResult, type ReadView } from './reads'\nimport type { ReadAddress } from './read-catalog'\nexport type ReadBlock = number | string | null\n"
for category, name in category_names.items():
 namespace_text += f'export interface {name}ReadNamespace {{\n'
 for row in rows:
  if row['category'] != category:
   continue
  parameters = []
  for key, kind in row['params'].items():
   annotation = {'integer': 'number', 'number': 'number | string', 'boolean': 'boolean', 'string': 'string', 'array': 'number[]' if key == 'netuids' else 'string[]'}[kind]
   if key.endswith('_ss58s'):
    annotation = 'ReadAddress[]'
   elif key.endswith('_ss58'):
    annotation = 'ReadAddress'
   if row['defaults'].get(key, 'required') is None:
    annotation += ' | null'
   parameters.append(f"{key}{'?' if key in row['defaults'] else ''}: {annotation}")
  if 'block' not in row['params']:
   parameters.append('block?: ReadBlock')
  methods = [row['name']]
  camel = row['name'].split('_')[0] + ''.join(part.title() for part in row['name'].split('_')[1:])
  if camel != row['name']:
   methods.append(camel)
  for method in methods:
   namespace_text += f"  {method}({', '.join(parameters)}): Promise<ReadResult<'{row['name']}'>>\n"
 namespace_text += '}\n'
namespace_text += '''
export function bindReadNamespace<T>(target: T, category: string, scope: (block?: ReadBlock) => Promise<ReadView>): T {
  for (const spec of READ_CATALOG) {
    if (spec.category !== category) continue
    const camel = spec.name.replace(/_([a-z])/g, (_, letter: string) => letter.toUpperCase())
    for (const method of new Set([spec.name, camel])) {
      if (method in (target as object)) continue
      Object.defineProperty(target, method, { enumerable: true, value: async (...args: unknown[]) => {
        const names = Object.keys(spec.params)
        const params = Object.fromEntries(names.flatMap((name, i) => args[i] === undefined ? [] : [[name, args[i]]]))
        const block = names.includes('block') ? undefined : args[names.length] as ReadBlock | undefined
        return dispatchRead(await scope(block), spec.name, params)
      } })
    }
  }
  return target
}
'''
namespace_target = root / 'sdk/bittensor-ts/src/read-namespaces.ts'
if args.check:
 if namespace_target.read_text() != namespace_text:
  raise SystemExit('TypeScript read namespaces drift; run scripts/generate-read-catalog.py')
else:
 namespace_target.write_text(namespace_text)
