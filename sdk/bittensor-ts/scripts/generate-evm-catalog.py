"""Generate portable precompile metadata from Python and canonical Solidity ABIs."""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT / "sdk/python"))
from bittensor.evm.precompiles import CALLER_ROLES, DEPRECATED_FUNCTIONS, PRECOMPILES

catalog = {}
for name, item in PRECOMPILES.items():
    canonical = ROOT / "precompiles/src/solidity" / item.abi_file.replace(".json", ".abi")
    catalog[name] = {
        "name": name, "index": item.index, "address": item.address,
        "description": item.description, "deprecated": item.deprecated,
        "abi": json.loads(canonical.read_text()),
        "callerRoles": CALLER_ROLES.get(name, {}),
        "deprecatedFunctions": DEPRECATED_FUNCTIONS.get(name, {}),
    }
output = "// Generated by scripts/generate-evm-catalog.py.\nexport const PRECOMPILE_CATALOG = " + json.dumps(catalog, indent=2) + " as const\n"
path = ROOT / "sdk/bittensor-ts/src/evm-catalog.ts"
parser = argparse.ArgumentParser()
parser.add_argument("--check", action="store_true")
args = parser.parse_args()
if args.check:
    if not path.exists() or path.read_text() != output:
        raise SystemExit("EVM catalog drift: run scripts/generate-evm-catalog.py")
else:
    path.write_text(output)
print(f"EVM catalog: {len(catalog)} precompiles")
