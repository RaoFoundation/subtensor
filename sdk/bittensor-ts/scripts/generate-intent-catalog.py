#!/usr/bin/env python3
"""Generate the portable intent input catalog from the Python source of truth.

Run with sdk/python/.venv/bin/python; --check detects newly added operations,
changed defaults, or changed input schemas without rewriting the snapshot.
"""

import argparse
from dataclasses import MISSING, fields
import json
import inspect
from pathlib import Path

from bittensor.intents import REGISTRY, list_tools
from bittensor.intents.hyperparameters import OWNER_HYPERPARAMETERS
from bittensor.hyperparams import kind_of, raw_bounds
from bittensor._generated import calls


def schema_type(schema):
    if "enum" in schema:
        return " | ".join(json.dumps(value) for value in schema["enum"])
    if "anyOf" in schema:
        return " | ".join(
            dict.fromkeys(schema_type(value) for value in schema["anyOf"])
        )
    kind = schema.get("type")
    if isinstance(kind, list):
        return " | ".join(dict.fromkeys(schema_type({"type": value}) for value in kind))
    if kind == "array":
        return "readonly (" + schema_type(schema.get("items", {})) + ")[]"
    return {
        "integer": "number | bigint | `${bigint}`",
        "number": "number",
        "string": "string",
        "boolean": "boolean",
        "object": "Readonly<Record<string, unknown>>",
    }.get(kind, "unknown")


def input_source(catalog):
    lines = [
        "// Generated by scripts/generate-intent-catalog.py; do not edit by hand.",
        "import type { Balance } from './balance'",
        "import type { Intent } from './intents'",
        "export type IntentAmountInput = Balance | number | string",
        "export interface BasketSwapLegInput { origin_netuid: number; dest_netuid: number; amount: IntentAmountInput; min_amount_out?: IntentAmountInput | null }",
        "export interface IntentTimepointInput { height: number; index: number }",
    ]
    names = {
        tool["name"]: "".join(part.title() for part in tool["name"].split("_"))
        for tool in catalog
    }
    for tool in catalog:
        properties = tool["input_schema"]["properties"]
        lines.append(f"/** {tool['summary'].replace('*/', '* /')} */")
        lines.append(f"export interface {names[tool['name']]}Input {{")
        for name, schema in properties.items():
            kind = schema_type(schema)
            if name in tool["money_fields"]:
                kind = "IntentAmountInput"
            elif name == "call":
                kind = "IntentJSON | Intent"
            elif name == "intents":
                kind = "readonly (IntentJSON | Intent)[]"
            elif name == "other_signatories":
                kind = "readonly string[]"
            elif name == "timepoint":
                kind = "IntentTimepointInput"
            elif name == "children":
                kind = "readonly (readonly [number | bigint | string, string])[]"
            elif name == "legs":
                kind = "readonly BasketSwapLegInput[]"
            elif name == "inner_op":
                kind = "keyof IntentInputMap"
            elif name == "weights":
                kind = "readonly number[] | Readonly<Record<number, number>>"
            elif name in ("uids", "salt", "subnets", "netuids", "mining_device_ids"):
                kind = "readonly number[]"
            elif tool["name"] == "set_hyperparameter" and name == "value":
                kind = "boolean | number | bigint | string"
            required = name in tool["input_schema"].get("required", [])
            nullable = (
                " | null"
                if name in tool["defaults"] and tool["defaults"][name] is None
                else ""
            )
            description = (
                schema.get("description", "").replace("*/", "* /").replace("\n", " ")
            )
            if description:
                lines.append(f"  /** {description} */")
            lines.append(f"  {name}{'' if required else '?'}: {kind}{nullable}")
        lines.append("}")
    lines.append("export interface IntentInputMap {")
    lines.extend(f"  {op}: {name}Input" for op, name in names.items())
    lines.append("}")
    lines.extend(
        f"export interface {name}JSON extends {name}Input {{ op: '{op}' }}"
        for op, name in names.items()
    )
    lines.extend(
        [
            "export type IntentJSON = "
            + " | ".join(f"{name}JSON" for name in names.values()),
            "export type IntentArguments<N extends keyof IntentInputMap> = keyof IntentInputMap[N] extends never ? [args?: Record<string, never>] : {} extends IntentInputMap[N] ? [args?: IntentInputMap[N]] : [args: IntentInputMap[N]]",
            "export type IntentBuilders = { readonly [N in keyof IntentInputMap]: (...args: IntentArguments<N>) => Intent }",
            "",
        ]
    )
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    catalog = []
    for tool in list_tools():
        cls = REGISTRY[tool["name"]]
        catalog.append(
            {
                **tool,
                "mev_shield_default": cls.mev_shield_default,
                "mev_shield_required": cls.mev_shield_required,
                "all_amount_fields": list(cls.all_amount_fields),
                "defaults": {
                    field.name: field.default
                    if field.default is not MISSING
                    else field.default_factory()
                    for field in fields(cls)
                    if field.default is not MISSING
                    or field.default_factory is not MISSING
                },
                "money_fields": [
                    field.name for field in fields(cls) if "Money" in str(field.type)
                ],
            }
        )
    source = (
        "// Generated by scripts/generate-intent-catalog.py; do not edit by hand.\n"
        "// Money inputs are exact decimal asset amounts; use bigint only for raw integer fields.\n"
        "export const INTENT_CATALOG = "
        + json.dumps(catalog, ensure_ascii=False, indent=2)
        + " as const\n"
    )
    hyperparameters = {
        name: {
            "call": fn,
            "params": list(inspect.signature(getattr(calls.AdminUtils, fn)).parameters),
            "kind": kind_of(name),
            "minimum": str(raw_bounds(name)[0]),
            "maximum": str(raw_bounds(name)[1]),
        }
        for name, (fn, _) in OWNER_HYPERPARAMETERS.items()
    }
    hyperparameter_source = (
        "// Generated by scripts/generate-intent-catalog.py; do not edit by hand.\n"
        "export const OWNER_HYPERPARAMETER_CATALOG = "
        + json.dumps(hyperparameters, indent=2)
        + " as const\n"
    )
    for filename, content in [
        ("intent-catalog.ts", source),
        ("intent-hyperparameter-catalog.ts", hyperparameter_source),
        ("intent-inputs.ts", input_source(catalog)),
    ]:
        destination = Path(__file__).resolve().parent.parent / "src" / filename
        if args.check:
            if not destination.exists() or destination.read_text() != content:
                raise SystemExit(
                    f"{filename} drift; run scripts/generate-intent-catalog.py"
                )
        else:
            destination.write_text(content)


if __name__ == "__main__":
    main()
