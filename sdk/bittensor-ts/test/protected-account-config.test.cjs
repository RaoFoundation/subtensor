'use strict'
const test = require('node:test')
const assert = require('node:assert/strict')
const config = require('../dist/protected-account-config')
const { MemoryJsonStore, BrowserJsonStore } = require('../dist/preferences')
const { blake2_256 } = require('../dist/crypto')
const chainA = '0x' + 'ab'.repeat(32), chainB = '0x' + 'cd'.repeat(32)
const identity = { accountId(address) { const match = /^(?:id|alias):(\d+)$/.exec(address); if (!match || Number(match[1]) > 255) throw new Error('invalid account'); return new Uint8Array(32).fill(Number(match[1])) }, hash: blake2_256, ss58Encode: bytes => `id:${bytes[0]}` }
const record = (fields = {}) => ({ controller_wallet: 'main', controller_ss58: 'id:1', protected_ss58: 'id:2', delay_blocks: 10800, allows: ['Staking'], ...fields })

test('protected delay parsing and legacy pure derivation match release vectors', () => {
  assert.equal(config.parseDelayToBlocks('36h'), 10800)
  assert.equal(config.parseDelayToBlocks('2d'), 14400)
  assert.equal(config.parseDelayToBlocks('10800'), 10800)
  assert.equal(config.parseDelayToBlocks(10800), 10800)
  assert.equal(config.parseDelayToBlocks('1 minute', 0.25), 240)
  assert.equal(config.parseDelayToBlocks('5s', 2), 2)
  assert.equal(config.parseDelayToBlocks('3s', 2), 2)
  for (const delay of [0, -1, NaN, Infinity, 1.5, 4294967296, '', '0h', '-1h', 'invalid']) assert.throws(() => config.parseDelayToBlocks(delay))
  assert.throws(() => config.parseDelayToBlocks('1h', 0))
  assert.equal(config.defaultProtectedName('main'), 'main-protected')
  assert.equal(config.blocksToLocalEta(0), 'now')
  assert.match(config.blocksToLocalEta(5, 12, new Date(0)), /^~1m /)
  const derived = config.deriveLegacyPureAccountId(identity, new Uint8Array(32).fill(12), { height: 17, ext_index: 2, proxy_type_scale: 3, index: 9 })
  assert.equal(Buffer.from(derived).toString('hex'), 'b5cc23966887d8f2b052ab1cdd660d081b97d7cb8768d8e1f02b73cdfa5724dd')
  assert.throws(() => config.deriveLegacyPureAccountId(identity, new Uint8Array(31), { height: 17, ext_index: 2 }), /32 bytes/)
  assert.throws(() => config.deriveLegacyPureAccountId(identity, new Uint8Array(32), { height: 17, ext_index: 2, proxy_type_scale: 256 }), /u8/)
  assert.throws(() => config.deriveLegacyPureSs58(identity, 'id:1', { height: 1, ext_index: 0, proxy_type: 'Staking' }), /Any/)
})

// PROTECTED_REGRESSION: instant protected-account allows must never grant immediate free-balance or proxy-management authority; changes require explicit human approval.
test('protected allows reject authority that bypasses the withdrawal delay', () => {
  assert.deepEqual(config.resolveAllowItems(['staking', 'childkeys', 'basket-swaps', 'basket']), ['Staking', 'ChildKeys', 'BasketTrading'])
  for (const item of Object.keys(config.FORBIDDEN_ALLOW_ITEMS)) assert.throws(() => config.resolveAllowItem(item), /refused/)
  assert.throws(() => config.resolveAllowItem('crowdloan'), /no suitably narrow/)
  const allowed = record({ allows: ['Staking', 'ChildKeys'], pending_allows: ['Weights'] })
  assert.equal(config.instantProxyTypeFor(identity, 'remove_stake', allowed), 'Staking')
  assert.equal(config.instantProxyTypeFor(identity, 'set_children', allowed), 'ChildKeys')
  for (const op of ['transfer', 'add_proxy', 'remove_proxies', 'set_weights']) assert.equal(config.instantProxyTypeFor(identity, op, allowed), undefined)
  assert.equal(config.instantProxyTypeFor(identity, 'remove_stake', allowed, { intent: { claim: true } }), undefined)
  assert.equal(config.instantProxyTypeFor(identity, 'set_hyperparameter', record({ allows: ['Owner'] }), { intent: { name: 'registration_allowed' } }), undefined)
  const separate = record({ allow_key_ss58: 'id:3' })
  assert.equal(config.instantProxyTypeFor(identity, 'add_stake', separate, { dispatcher_ss58: 'id:1' }), undefined)
  assert.equal(config.instantProxyTypeFor(identity, 'add_stake', separate, { dispatcher_ss58: 'alias:3' }), 'Staking')
})

test('authority helpers distinguish live controller grants from separate allow keys', () => {
  const grants = [{ delegate: 'alias:1', proxy_type: 'Any', delay: 10800 }, { delegate: 'id:1', proxy_type: 'Any', delay: 1 }, { delegate: 'id:1', proxy_type: 'Lock', delay: 0 }, { delegate: 'id:3', proxy_type: 'Transfer', delay: 0 }]
  assert.deepEqual(config.controllerAnyDelays(identity, grants, 'id:1'), [10800, 1])
  assert.deepEqual(config.controllerGrantsBeforeDelay(identity, grants, 'id:1', 10800).map(row => row.delay), [1, 0])
  assert.deepEqual(config.defeatingZeroDelayProxies(identity, grants, 'id:1'), [])
  assert.deepEqual(config.defeatingZeroDelayProxies(identity, [...grants, { delegate: 'id:1', proxy_type: 'Any', delay: 0 }], 'alias:1'), ['Any'])
  assert.deepEqual(config.allowKeyGrants(identity, grants, 'id:1').map(row => row.proxy_type), ['Lock'])
  assert.equal(config.controllerHoldsAllows(identity, record({ allow_key_ss58: 'alias:1' }), 'id:1'), true)
  assert.deepEqual(config.controllerOwnedAllowTypes(identity, record({ allow_key_ss58: 'id:3' }), 'id:1'), [])
  assert.deepEqual(config.controllerOwnedAllowTypes(identity, record(), 'id:1'), ['Staking'])
  const newGrant = { delegate: 'id:4', proxy_type: 'Any', delay: 10800 }, rotation = { new_controller_ss58: 'alias:4', old_controller_ss58: 'id:1', delay_blocks: 10800 }
  assert.equal(config.rotationComplete(identity, [newGrant, grants[2]], rotation), false)
  assert.equal(config.rotationComplete(identity, [newGrant, grants[3]], rotation), true)
  assert.equal(config.protectedSetupPending({ setup: { status: 'pending' } }), true)
  assert.equal(config.protectedSetupPending({ setup: { status: 'ready' }, coldkey_swap: { status: 'announced' } }), false)
})

test('nested pending grants and management payloads cannot disappear behind labels', () => {
  const grant = { op: 'add_proxy', delegate_ss58: 'id:3', proxy_type: 'Staking', delay: 0 }
  const nested = { index: 7, status: 'submitting', category: 'ordinary', inner_op: 'batch', inner_args: { intents: [{ op: 'execute_proxy_announced', inner_op: 'add_proxy', inner_args: grant }] } }
  assert.equal(config.announcementProxyGrants(nested).length, 1)
  const labels = config.pendingAllowGrantLabels(identity, [nested, { ...nested, index: 8, status: 'cancelled' }], 'alias:3')
  assert.deepEqual(labels, ['#7 allow:Staking → id:3'])
  assert.deepEqual(config.pendingAllowGrantLabels(identity, [nested], 'id:4'), [])
  const blockers = config.allowKeyChangeBlockers(identity, { old_allow_key_ss58: 'id:3', new_allow_key_ss58: 'id:4', allows: ['Staking'], pending_allows: ['Weights'], pending_allow_announcements: labels, delegations: [{ delegate: 'id:3', proxy_type: 'Lock', delay: 0 }] })
  assert.equal(blockers.length, 4)
  assert.deepEqual(config.allowKeyChangeBlockers(identity, { old_allow_key_ss58: 'id:3', new_allow_key_ss58: 'alias:3', allows: ['Staking'], pending_allows: [], delegations: [] }), [])
  const batch = { op: 'batch', intents: [grant] }
  assert.match(config.protectedManagementPath(batch), /batch\[0\].add_proxy/)
  assert.throws(() => config.assertProtectedManagementAllowed({ category: 'ordinary' }, batch), /unmanaged/)
  assert.equal(config.isProtectedManagementReceipt({ category: 'allow:Staking' }, grant), true)
  assert.equal(config.isProtectedManagementReceipt({ category: 'allow:Any' }, grant), false)
  assert.equal(config.isProtectedManagementReceipt({ category: 'allow:Staking' }, { ...grant, delay: 4 }), false)
  config.assertProtectedManagementAllowed({ category: 'allow:Staking' }, grant)
})

test('protected config isolates chain scopes and requires explicit legacy binding', async () => {
  const storage = new MemoryJsonStore(), book = new config.ProtectedAccountStore(storage, identity)
  await book.upsert(record())
  assert.equal(await book.getByController('main', chainA), undefined)
  await book.upsert(record({ genesis_hash: chainA.toUpperCase().replace('0X', '0x'), protected_ss58: 'id:5' }))
  await book.upsert(record({ genesis_hash: chainB, protected_ss58: 'id:6' }))
  assert.equal((await book.getByController('main', chainA)).protected_ss58, 'id:5')
  assert.equal((await book.getByProtectedAddress('alias:5', chainA)).controller_wallet, 'main')
  const before = await book.list()
  await assert.rejects(book.bindLegacy('main', chainA), /legacy and scoped records preserved/)
  assert.deepEqual(await book.list(), before)
  await book.remove('main', chainA)
  assert.equal((await book.bindLegacy('main', chainA)).genesis_hash, chainA)
  assert.equal(await book.getByController('main'), undefined)
  assert.equal((await book.getByController('main', chainB)).protected_ss58, 'id:6')
})

test('config rotation preserves conflicting and other-chain bindings and failed writes', async () => {
  const storage = new MemoryJsonStore(), book = new config.ProtectedAccountStore(storage, identity)
  await book.upsert(record({ genesis_hash: chainA }))
  await book.upsert(record({ controller_wallet: 'destination', protected_ss58: 'id:7', genesis_hash: chainA }))
  const before = await book.list()
  await assert.rejects(book.moveController('main', 'destination', { genesis_hash: chainA, controller_ss58: 'id:4' }), /both bindings preserved/)
  assert.deepEqual(await book.list(), before)
  await book.remove('destination', chainA)
  await book.upsert(record({ controller_wallet: 'destination', protected_ss58: 'id:7', genesis_hash: chainB }))
  const failed = new config.ProtectedAccountStore({ read: key => storage.read(key), write: async () => { throw new Error('disk full') } }, identity)
  await assert.rejects(failed.moveController('main', 'destination', { genesis_hash: chainA }), /disk full/)
  assert(await book.getByController('main', chainA))
  const moved = await book.moveController('main', 'destination', { genesis_hash: chainA, controller_ss58: 'id:4' })
  assert.equal(moved.controller_ss58, 'id:4')
  assert.equal((await book.getByController('destination', chainB)).protected_ss58, 'id:7')
  assert.equal(await book.getByController('main', chainA), undefined)
})

test('setup reservations atomically select one creator and retain uncertain work', async () => {
  const storage = new MemoryJsonStore(), left = new config.ProtectedAccountStore(storage, identity), right = new config.ProtectedAccountStore(storage, identity)
  const reservation = { controller_wallet: 'main', controller_ss58: 'id:1', genesis_hash: chainA, delay_blocks: 10, index: 0, allow_types: [], status: 'submitting' }
  const claims = await Promise.all([left.reserveSetup(reservation), right.reserveSetup(reservation)])
  assert.equal(claims.filter(row => row.created).length, 1)
  await left.saveSetup({ ...reservation, status: 'uncertain', extrinsic_hash: '0x01' })
  assert.equal((await right.reserveSetup({ ...reservation, delay_blocks: 20 })).created, false)
  assert.equal((await right.getSetup('main', chainA)).delay_blocks, 10)
  assert.equal(await right.getSetup('main', chainB), undefined)
  assert.equal((await right.reserveSetup({ ...reservation, genesis_hash: chainB })).created, true)
  await left.saveSetup({ ...reservation, status: 'failed' })
  assert.equal((await right.reserveSetup(reservation)).created, false)
  await left.removeSetup('main', chainA)
  assert.equal((await right.reserveSetup(reservation)).created, true)
  await left.removeSetup('main', chainA)
  assert(await right.getSetup('main', chainB))
})

test('two config instances serialize custom stores and invalid data is never overwritten', async () => {
  const memory = new MemoryJsonStore(), custom = { read: key => memory.read(key), write: (key, value) => memory.write(key, value) }
  const left = new config.ProtectedAccountStore(custom, identity), right = new config.ProtectedAccountStore(custom, identity)
  await Promise.all([left.upsert(record({ controller_wallet: 'one', genesis_hash: chainA })), right.upsert(record({ controller_wallet: 'two', genesis_hash: chainA }))])
  assert.equal((await left.list()).length, 2)
  await memory.write('protected', { broken: true })
  await assert.rejects(left.upsert(record()), /invalid protected-account store/)
  assert.deepEqual(await memory.read('protected'), { broken: true })
})

