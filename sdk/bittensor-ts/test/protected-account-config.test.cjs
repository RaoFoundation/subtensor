test('migration reservation permits one submitter and preserves concurrent setup progress', async () => {
  const storage = new MemoryJsonStore(), left = new config.ProtectedAccountStore(storage, identity), right = new config.ProtectedAccountStore(storage, identity)
  await left.upsert(record({ genesis_hash: chainA, setup: { status: 'migration_pending' } }))
  const results = await Promise.all([left.reserveMigration('main', chainA, 'id:2'), right.reserveMigration('main', chainA, 'alias:2')])
  assert.equal(results.filter(result => result.created).length, 1)
  await right.patch('main', chainA, { setup: { status: 'waiting_for_migration' }, pending_allows: ['Staking'] })
  const saved = await left.getByController('main', chainA)
  assert.equal(saved.coldkey_swap.status, 'submitting')
  assert.equal(saved.setup.status, 'waiting_for_migration')
  assert.deepEqual(saved.pending_allows, ['Staking'])
  for (const status of ['submitting', 'uncertain', 'awaiting_approval', 'announced', 'executed']) {
    await left.patch('main', chainA, { coldkey_swap: { status } })
    assert.equal((await right.reserveMigration('main', chainA, 'id:2')).created, false, status)
  }
  await left.patch('main', chainA, { coldkey_swap: { status: 'failed' } })
  assert.equal((await right.reserveMigration('main', chainA, 'id:2')).created, true)
  await assert.rejects(left.reserveMigration('main', chainA, 'id:3'), /differs/)
  await assert.rejects(left.reserveMigration('main', chainB, 'id:2'), /not found/)
})

test('stale migration receipts cannot clear a newer claim and workflow patches cannot rebind identities', async () => {
  const storage = new MemoryJsonStore(), book = new config.ProtectedAccountStore(storage, identity)
  await book.upsert(record({ genesis_hash: chainA, coldkey_swap: { status: 'uncertain', receipt: { extrinsicHash: 'old' } } }))
  await book.patch('main', chainA, { coldkey_swap: { status: 'failed' } }, { status: 'uncertain', extrinsicHash: 'old' })
  await book.reserveMigration('main', chainA, 'id:2')
  const current = await book.patch('main', chainA, { coldkey_swap: { status: 'failed' } }, { status: 'uncertain', extrinsicHash: 'old' })
  assert.equal(current.coldkey_swap.status, 'submitting')
  for (const fields of [{ controller_wallet: 'other' }, { genesis_hash: chainB }, { genesis_hash: undefined }, { protected_ss58: 'id:9' }]) await assert.rejects(book.patch('main', chainA, fields), /identity cannot change/)
  assert.equal((await book.patch('main', chainA, { protected_ss58: 'alias:2' })).protected_ss58, 'id:2')
  assert.equal((await book.getByController('main', chainA)).coldkey_swap.status, 'submitting')
})

test('concurrent creation recovery preserves an already claimed migration and rejects conflicting identities', async () => {
  const storage = new MemoryJsonStore(), first = new config.ProtectedAccountStore(storage, identity), resumed = new config.ProtectedAccountStore(storage, identity)
  const initial = record({ genesis_hash: chainA, coldkey_swap: { status: 'pending' }, setup: { status: 'pending' } })
  await first.bindCreated(initial)
  await first.reserveMigration('main', chainA, 'id:2')
  await first.patch('main', chainA, { setup: { status: 'waiting_for_migration' } })
  const recovered = await resumed.bindCreated({ ...initial, controller_ss58: 'alias:1', protected_ss58: 'alias:2' })
  assert.equal(recovered.coldkey_swap.status, 'submitting')
  assert.equal(recovered.setup.status, 'waiting_for_migration')
  assert.equal((await resumed.reserveMigration('main', chainA, 'id:2')).created, false)
  for (const fields of [{ controller_ss58: 'id:3' }, { protected_ss58: 'id:4' }]) await assert.rejects(resumed.bindCreated({ ...initial, ...fields }), /conflicts/)
  assert.deepEqual(await first.getByController('main', chainA), recovered)
  await resumed.bindCreated({ ...initial, genesis_hash: chainB, protected_ss58: 'id:4' })
  assert.equal((await first.getByController('main', chainB)).protected_ss58, 'id:4')
})
