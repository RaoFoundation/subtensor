# --- MDX helpers -----------------------------------------------------------


def mdx_escape(text: str) -> str:
    """Escape MDX-active characters ({, <) outside inline code spans."""
    parts = text.split("`")
    for i in range(0, len(parts), 2):
        parts[i] = parts[i].replace("{", "\\{").replace("<", "\\<")
    return "`".join(parts)


def cell(text: str) -> str:
    """Make text safe inside a markdown table cell."""
    return mdx_escape(text.replace("|", "\\|").replace("\n", " ").strip())


def frontmatter(title: str, description: str) -> str:
    return "---\ntitle: %s\ndescription: %s\n---\n\n%s\n" % (
        json.dumps(title),
        json.dumps(description),
        GENERATED_NOTE,
    )


def docs_markdown_url(docs_url: str) -> str:
    """Agent-fetchable markdown for a `/docs/...` page URL."""
    if docs_url == "/docs" or docs_url == "/docs/":
        return "/llms.mdx/docs/content.md"
    if not docs_url.startswith("/docs/"):
        raise ValueError(f"expected /docs/... path, got {docs_url!r}")
    return f"/llms.mdx{docs_url}/content.md"


def with_code_urls(path: str, url: str) -> dict[str, str]:
    """HTML viewer URL plus plain-text raw URL for the same file."""
    return {"url": url, "raw_url": f"/code/raw/{path}"}


def kebab(name: str) -> str:
    return name.replace("_", "-")


def body_after_summary(doc: str) -> str:
    """Docstring minus its first line — the page frontmatter already shows it."""
    _, _, rest = doc.partition("\n")
    return rest.strip()


# --- Parameter rendering ---------------------------------------------------


def schema_type(fragment: dict) -> str:
    """Human-readable type from a JSON-schema property fragment."""
    if "anyOf" in fragment:
        return "number \\| `\"all\"`"
    t = fragment.get("type", "any")
    if isinstance(t, list):
        return " \\| ".join(t)
    if t == "array":
        items = fragment.get("items", {}).get("type")
        return f"array of {items}" if items else "array"
    return t


def cli_flag(field_name: str) -> str:
    if field_name.endswith("_ss58"):
        base = field_name[: -len("_ss58")]
    else:
        base = field_name.replace("_ss58", "")
    return "--" + base.replace("_", "-")


def cli_placeholder(field_name: str, fragment: dict) -> str:
    if field_name.endswith("_ss58"):
        return "<ss58|name>"
    if "anyOf" in fragment:
        return "<amount|all>"
    t = fragment.get("type")
    if t == "integer":
        return "<int>"
    if t == "number":
        return "<number>"
    if t == "array":
        if fragment.get("items", {}).get("type") == "object":
            return "'<json-array>'"
        return "<a,b,c>"
    if t == "object":
        return "'<json>'"
    return "<value>"


def cli_arg(field_name: str, fragment: dict) -> str:
    """Full CLI arg for a field. Typer bools are ``--flag/--no-flag``."""
    if fragment.get("type") == "boolean":
        # Match the Typer bool pattern in cli (same as query --lite/--no-lite).
        flag = cli_flag(field_name)
        return f"{flag}/--no-{flag.removeprefix('--')}"
    return f"{cli_flag(field_name)} {cli_placeholder(field_name, fragment)}"


def py_placeholder(field_name: str, fragment: dict) -> str:
    if field_name == "netuid":
        return "1"
    if field_name.endswith("_ss58"):
        return '"5F..."'
    if "anyOf" in fragment:
        return "1.0"
    t = fragment.get("type")
    if t == "integer":
        return "0"
    if t == "number":
        return "1.0"
    if t == "boolean":
        return "True"
    if t == "array":
        return "[...]"
    if t == "object":
        return "{...}"
    return '"..."'


def params_table(schema: dict) -> str:
    props: dict = schema.get("properties", {})
    if not props:
        return "This operation takes no parameters.\n"
    required = set(schema.get("required", []))
    lines = [
        "| Parameter | Type | Required | Description |",
        "| --- | --- | --- | --- |",
    ]
    for name, fragment in props.items():
        lines.append(
            "| `%s` | %s | %s | %s |"
            % (
                name,
                schema_type(fragment),
                "yes" if name in required else "no",
                cell(fragment.get("description", "")),
            )
        )
    return "\n".join(lines) + "\n"


